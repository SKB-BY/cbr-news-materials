#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build map/data.js for the static map from companies.csv + map/links.json (stdlib only).

Usage: python3 scripts/build_map_data.py   (run from the repository root)
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ["id", "kind", "region", "country", "name", "sponsor", "role_focus", "url", "source_url",
          "customers", "customers_source", "ubo_name", "ubo_source", "red_flags", "red_flags_source",
          "tier_level", "mentions"]


def main():
    rows = list(csv.DictReader(open(ROOT / "companies.csv", encoding="utf-8")))
    nodes = []
    for r in rows:
        n = {k: r.get(k, "") for k in FIELDS}
        # threat-analysis objects: rows that the register itself marks «объект анализа угроз»
        n["threat"] = "объект анализа угроз" in (r.get("role_focus") or "")
        nodes.append(n)
    links = json.load(open(ROOT / "map" / "links.json", encoding="utf-8"))
    ids = {n["id"] for n in nodes} | {x["id"] for x in links["external"]}
    for l in links["links"]:
        assert l["from"] in ids and l["to"] in ids, l
    data = {"nodes": nodes, "external": links["external"], "links": links["links"]}
    (ROOT / "map" / "data.js").write_text(
        "// generated by scripts/build_map_data.py from companies.csv and map/links.json\nwindow.MAP_DATA="
        + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(len(nodes), "nodes,", len(links["external"]), "external,", len(links["links"]), "links")


if __name__ == "__main__":
    main()
